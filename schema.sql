-- KOMSI RUPA LIBRARY — Supabase setup / repair script
-- Run in Supabase SQL Editor. This script does not drop the artworks table or its data.
-- Project bucket: rupa-library. Public bucket means anyone with a file URL can view/download those files.

create table if not exists public.artworks (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Artwork',
  description text not null default '',
  creator text not null default 'KOMSI Library',
  image_url text,
  file_url text not null,
  preview_url text,
  file_name text not null default '',
  file_size bigint,
  mime_type text,
  uploaded_by uuid references auth.users(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  tags text[] not null default '{}',
  created_at timestamptz not null default now()
);

-- Compatibility columns for tables created by an earlier version.
alter table public.artworks add column if not exists creator text not null default 'KOMSI Library';
alter table public.artworks add column if not exists image_url text;
alter table public.artworks add column if not exists file_url text;
alter table public.artworks add column if not exists preview_url text;
alter table public.artworks add column if not exists file_name text default '';
alter table public.artworks add column if not exists file_size bigint;
alter table public.artworks add column if not exists mime_type text;
alter table public.artworks add column if not exists uploaded_by uuid references auth.users(id) on delete set null;
alter table public.artworks add column if not exists created_by uuid references auth.users(id) on delete set null;
alter table public.artworks add column if not exists tags text[] not null default '{}';

-- Keep image_url populated for legacy records when a file URL exists.
update public.artworks set image_url = coalesce(image_url, preview_url, file_url) where image_url is null;

alter table public.artworks enable row level security;
grant select on public.artworks to anon, authenticated;
grant insert, update, delete on public.artworks to authenticated;
grant usage, select on sequence public.artworks_id_seq to authenticated;

drop policy if exists "Public can read artworks" on public.artworks;
drop policy if exists "Public can view artworks" on public.artworks;
create policy "Public can read artworks" on public.artworks for select to anon, authenticated using (true);

drop policy if exists "Signed-in users can insert artworks" on public.artworks;
drop policy if exists "Admin can insert artworks" on public.artworks;
create policy "Admin can insert artworks" on public.artworks for insert to authenticated
with check (auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid);

drop policy if exists "Signed-in users can update artworks" on public.artworks;
drop policy if exists "Admin can update artworks" on public.artworks;
create policy "Admin can update artworks" on public.artworks for update to authenticated
using (auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid)
with check (auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid);

drop policy if exists "Signed-in users can delete artworks" on public.artworks;
drop policy if exists "Admin can delete artworks" on public.artworks;
create policy "Admin can delete artworks" on public.artworks for delete to authenticated
using (auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid);

-- Storage: upload/read permissions for the dedicated admin and public viewing.
drop policy if exists "Public can view rupa files" on storage.objects;
create policy "Public can view rupa files" on storage.objects for select to anon, authenticated
using (bucket_id = 'rupa-library');

drop policy if exists "Signed-in users can upload rupa files" on storage.objects;
drop policy if exists "Admin can upload rupa files" on storage.objects;
create policy "Admin can upload rupa files" on storage.objects for insert to authenticated
with check (bucket_id = 'rupa-library' and auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid);

drop policy if exists "Uploader can update rupa files" on storage.objects;
drop policy if exists "Admin can update rupa files" on storage.objects;
create policy "Admin can update rupa files" on storage.objects for update to authenticated
using (bucket_id = 'rupa-library' and auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid)
with check (bucket_id = 'rupa-library' and auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid);

drop policy if exists "Uploader can delete rupa files" on storage.objects;
drop policy if exists "Admin can delete rupa files" on storage.objects;
create policy "Admin can delete rupa files" on storage.objects for delete to authenticated
using (bucket_id = 'rupa-library' and auth.uid() = 'b520cf6e-be06-4338-976d-8604877fd632'::uuid);
